/** Text of any value, without turning 0 or false into an empty string. */
function text(value) {
  if (value === null || value === undefined) return ''
  return typeof value === 'string' ? value : String(value)
}

function hasText(value) {
  return text(value).trim() !== ''
}

function listOf(value) {
  return Array.isArray(value) ? value : []
}

/** One repeated-row object with exactly the given columns, as strings. */
function normalizeRow(row, fields) {
  const result = {}
  for (const field of fields) result[field.key] = text(row?.[field.key])
  return result
}

/** True when a repeated entry carries anything at all. */
function rowHasContent(row) {
  return Object.values(row || {}).some((value) => hasText(value))
}

/** "OCTOBER 2026" - the month and year the report is being prepared. */
export function currentMonthYear(now = new Date()) {
  return now
    .toLocaleDateString('en-US', { month: 'long', year: 'numeric' })
    .toUpperCase()
}

/** A blank body section. */
export function emptySection() {
  return { text: '', subsections: [], tables: [] }
}

/**
 * A blank table: `columns` column headings and two empty rows, so the proponent can start
 * typing straight away.
 */
export function emptyTable(columns = []) {
  const headers = columns.length ? columns.slice() : ['Column 1', 'Column 2']
  return {
    caption: '',
    note: '',
    columns: headers,
    rows: [headers.map(() => ''), headers.map(() => '')],
  }
}

/** A blank subsection. */
export function emptySubsection(heading = '') {
  return { heading, text: '' }
}

/** A blank appendix entry. */
export function emptyAppendix() {
  return { title: '', text: '' }
}

/** A blank Terminal Report: every field present, every repeated section empty. */
export function emptyTerminalReport() {
  const report = {}
  for (const field of TERMINAL_COVER_FIELDS) report[field.key] = ''
  for (const field of TERMINAL_FINANCIAL_FIELDS) report[field.key] = ''
  report.summaryRows = []
  report.summaryAccomplishmentsTitle = ''
  report.summaryObjectives = []
  for (const field of TERMINAL_NARRATIVE_FIELDS) report[field.key] = ''
  for (const list of TERMINAL_LISTS) report[list.key] = []
  for (const section of TERMINAL_BODY_SECTIONS) {
    if (section.kind === 'text') report[section.key] = emptySection()
  }
  report.literatureCited = []
  report.appendices = []
  report.appendixTables = []
  return report
}


/** Normalizes one table to its stored shape (columns and rows as strings). */
function normalizeTable(table) {
  const source = table && typeof table === 'object' ? table : {}
  const columns = listOf(source.columns).map((column) => text(column))
  const headers = columns.length ? columns : ['Column 1', 'Column 2']
  const rows = listOf(source.rows).map((row) => {
    const cells = listOf(row).slice(0, headers.length).map((cell) => text(cell))
    while (cells.length < headers.length) cells.push('')
    return cells
  })
  return { caption: text(source.caption), note: text(source.note), columns: headers, rows }
}

/** Normalizes one body section to its stored shape. */
function normalizeSection(section) {
  const source = section && typeof section === 'object' ? section : {}
  return {
    text: text(source.text),
    subsections: listOf(source.subsections).map((subsection) =>
      normalizeRow(subsection, TERMINAL_SUBSECTION_FIELDS)
    ),
    tables: listOf(source.tables).map(normalizeTable),
  }
}

/** True when a table carries at least one filled cell (a caption alone is not a table). */
export function tableHasContent(table) {
  return listOf(table?.rows).some((row) => listOf(row).some((cell) => hasText(cell)))
}

/** True when a body section holds text, in the section itself or in a subsection. */
export function sectionHasText(section) {
  if (hasText(section?.text)) return true
  return listOf(section?.subsections).some((subsection) => hasText(subsection?.text))
}

/** True when a summary item carries a value (an item left empty is not printed). */
export function summaryRowHasValue(row) {
  return hasText(row?.detail)
}

/**
 * The report with every field in its stored shape, without dropping anything. Used by the
 * document viewer so a stored report is always rendered completely, even if it was saved
 * before a field existed.
 */
export function normalizeTerminalReport(report) {
  const state = emptyTerminalReport()
  const source = report && typeof report === 'object' ? report : {}

  for (const field of TERMINAL_COVER_FIELDS) state[field.key] = text(source[field.key])
  for (const field of TERMINAL_FINANCIAL_FIELDS) state[field.key] = text(source[field.key])
  state.summaryAccomplishmentsTitle = text(source.summaryAccomplishmentsTitle)
  state.summaryRows = normalizeSummaryRows(source.summaryRows)
  state.summaryObjectives = listOf(source.summaryObjectives).map((row) =>
    normalizeRow(row, TERMINAL_OBJECTIVE_FIELDS)
  )
  for (const field of TERMINAL_NARRATIVE_FIELDS) state[field.key] = text(source[field.key])
  for (const list of TERMINAL_LISTS) {
    state[list.key] = listOf(source[list.key]).map((row) => normalizeRow(row, list.fields))
  }
  for (const section of TERMINAL_BODY_SECTIONS) {
    if (section.kind === 'text') state[section.key] = normalizeSection(source[section.key])
  }
  state.literatureCited = listOf(source.literatureCited).map((row) =>
    normalizeRow(row, TERMINAL_REFERENCE_FIELDS)
  )
  state.appendices = listOf(source.appendices).map((row) =>
    normalizeRow(row, TERMINAL_APPENDIX_FIELDS)
  )
  state.appendixTables = listOf(source.appendixTables).map(normalizeTable)
  return state
}

/**
 * The report as it is stored: the same shape, with everything the proponent left empty
 * removed - empty subsections, tables without cells, empty list entries, empty summary
 * items and empty appendices. Nothing is added: the payload is exactly what the form
 * holds.
 */
export function terminalReportPayload(report) {
  const state = normalizeTerminalReport(report)

  state.summaryRows = state.summaryRows.filter(summaryRowHasValue)
  state.summaryObjectives = state.summaryObjectives.filter(rowHasContent)
  for (const list of TERMINAL_LISTS) state[list.key] = state[list.key].filter(rowHasContent)
  state.literatureCited = state.literatureCited.filter(rowHasContent)
  state.appendices = state.appendices.filter(rowHasContent)

  for (const section of TERMINAL_BODY_SECTIONS) {
    if (section.kind !== 'text') continue
    const value = state[section.key]
    value.subsections = value.subsections.filter((subsection) => hasText(subsection.text))
    value.tables = value.tables.filter(tableHasContent)
  }
  state.appendixTables = state.appendixTables.filter(tableHasContent)
  return state
}


/**
 * The form state of a Terminal Report: the saved content when there is one, otherwise the
 * blank report prefilled with the project information RPIS already holds, plus the
 * subsection headings and tables the official format and the RPIS requirements expect as a
 * starting point.
 *
 * Saved values always win, so reopening a draft restores exactly what the proponent
 * entered. Only reliable project data is prefilled (project title, leader and gender,
 * agency, address and email, cooperating agency, duration): budget figures, base station,
 * area covered and results are left to the proponent, because the system never invents
 * them.
 */
export function terminalReportFormState(saved, proposal, { today = new Date() } = {}) {
  const state = normalizeTerminalReport(saved)
  const hasSaved = saved && typeof saved === 'object'
  const p = proposal && typeof proposal === 'object' ? proposal : {}

  // The cover page takes its titles and date from the project and submission records RPIS
  // already holds. The project team (the authors) is entered by the proponent and is never
  // auto-populated, so the proponent chooses which members appear as authors.
  const prefill = {
    programTitle: text(p.programTitle),
    projectTitle: text(p.projectTitle),
    collaborators: text(p.cooperatingAgencies),
    submissionMonthYear: currentMonthYear(today),
  }
  for (const [key, value] of Object.entries(prefill)) {
    if (!hasText(state[key])) state[key] = value
  }

  // Fill any fixed summary row the report does not hold yet from the project record; a value
  // already saved on the report wins, so a reopened draft keeps what the proponent entered.
  const summaryPrefill = new Map(standardSummaryRows(p).map((row) => [row.label, row.detail]))
  for (const row of state.summaryRows) {
    const value = summaryPrefill.get(row.label)
    if (value && !hasText(row.detail)) row.detail = value
  }
  if (!state.summaryAccomplishmentsTitle) {
    state.summaryAccomplishmentsTitle = ''
  }

  for (const section of TERMINAL_BODY_SECTIONS) {
    if (section.kind !== 'text') continue
    const value = state[section.key]
    const starters = TERMINAL_STARTER_SUBSECTIONS[section.key] || []
    if (!value.subsections.length && starters.length) {
      value.subsections = starters.map((heading) => emptySubsection(heading))
    }
    const starterTable = TERMINAL_STARTER_TABLES[section.key]
    if (!value.tables.length && starterTable) {
      const table = emptyTable(starterTable.columns)
      table.caption = starterTable.caption
      value.tables = [table]
    }
  }
  return state
}

/**
 * The rows of the summary sheet's "Project Information" table: the items the official
 * format prints, plus the summary items the RPIS reporting requirements list. A value is
 * only filled in when RPIS already holds it.
 */
function standardSummaryRows(proposal) {
  const p = proposal && typeof proposal === 'object' ? proposal : {}
  const address =
    text(p.address) ||
    [text(p.addressMunicipality), text(p.addressProvince)].filter(hasText).join(', ')
  const email = text(p.proponent?.email) || text(p.contactValue)

  return [
    { label: 'Program Title', detail: text(p.programTitle) },
    { label: 'Project Title', detail: text(p.projectTitle) },
    { label: 'Project Leader/Gender', detail: joinedValue(text(p.projectLeader), text(p.projectLeaderSex)) },
    { label: 'Agency', detail: text(p.college) },
    { label: 'Address/Email', detail: joinedValue(address, email) },
    { label: 'Cooperating Agency', detail: text(p.cooperatingAgencies) },
    { label: 'Base Station', detail: '' },
    { label: 'Area Covered', detail: '' },
    { label: 'Data Collection', detail: '' },
    { label: 'Production Comparison', detail: '' },
  ].map((row) => normalizeRow(row, TERMINAL_SUMMARY_ROW_FIELDS))
}

/** Joins the non-empty parts with " / " - the way the summary prints a combined value. */
function joinedValue(...parts) {
  return parts
    .map((part) => text(part).trim())
    .filter((part) => part !== '')
    .join(' / ')
}

