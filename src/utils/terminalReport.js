/**
 * terminalReport.js
 * ---------------------------------------------------------------------------
 * The structured Terminal Report of the proponent side: the shape of the document, the
 * section list of the form, the values prefilled from the project record, the validation
 * rules, the save payload and the numbering the document renderer uses.
 *
 * The structure follows the official MSUN-Naawan terminal report format (the sample report
 * shipped with the reporting module): a cover page, the front matter (summary sheet,
 * acknowledgment, abstract with keywords, table of contents and the lists of tables,
 * figures, graphs, appendices and acronyms), the numbered body sections 1-7
 * (Introduction, Review of Related Literature, Methodology, Results and Discussion,
 * Conclusions and Recommendations, Literature Cited, Appendix) and the additional
 * sections 8-10 required by the RPIS reporting requirements (Problems Encountered, Output,
 * Utilization). Body sections carry their own numbered subsections and captioned tables.
 *
 * The report is stored on the existing terminal reporting row (report type
 * TERMINAL_REPORT of quarterly_progress_reports, column terminal_report_json), so the
 * save / submit / authorization workflow stays exactly the one already in place.
 *
 * Nothing institutional is invented here: the letterhead text is the text printed on the
 * official report, and only project data RPIS already holds is prefilled.
 *
 * Run the rules with: npm test
 */

