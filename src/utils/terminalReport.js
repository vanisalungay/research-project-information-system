/**
 * Normalizes the summary rows to the fixed Project Information Details table, in order. An
 * older report that stored the split rows ("Project Leader" / "Gender", "Address" / "Email")
 * is folded into the combined rows, so a reopened draft keeps its values. A row the report
 * already holds that is none of the fixed (or legacy) rows is preserved as-is.
 *
 * <p>Every detail stays on the report itself: the proponent edits the Terminal Report copy,
 * so the original project record is never touched.
 */
function normalizeSummaryRows(sourceRows) {
  const stored = listOf(sourceRows).map((row) => normalizeRow(row, TERMINAL_SUMMARY_ROW_FIELDS))
  const at = (label) => {
    const wanted = label.toLowerCase()
    const found = stored.find((row) => row.label.trim().toLowerCase() === wanted)
    return found ? found.detail : ''
  }
  const values = {
    'Program Title': at('Program Title'),
    'Project Title': at('Project Title'),
    'Project Leader/Gender':
      at('Project Leader/Gender') || joinedValue(at('Project Leader'), at('Gender')),
    'Agency': at('Agency'),
    'Address/Email': at('Address/Email') || joinedValue(at('Address'), at('Email')),
    'Cooperating Agency': at('Cooperating Agency'),
    'Base Station': at('Base Station'),
    'Area Covered': at('Area Covered'),
    'Data Collection': at('Data Collection'),
    'Production Comparison': at('Production Comparison'),
  }
  const fixed = SUMMARY_FIXED_LABELS.map((label) => ({ label, detail: values[label] }))
  const consumed = new Set(
    [...SUMMARY_FIXED_LABELS, ...SUMMARY_LEGACY_LABELS].map((label) => label.toLowerCase()),
  )
  const extras = stored.filter((row) => row.label && !consumed.has(row.label.trim().toLowerCase()))
  return [...fixed, ...extras]
}

/** The report's summary rows with the fixed Project Information Details table ensured. */
export function terminalSummaryRows(rows) {
  return normalizeSummaryRows(rows)
}

/**
 * Formats a money value as "PHP 1,234.00". A value that already names the currency is kept as
 * stored, a non-numeric value is returned unchanged, and an empty value stays empty.
 */
export function formatPhpAmount(value) {
  const raw = text(value).trim()
  if (raw === '') return ''
  if (/php/i.test(raw)) return raw
  const number = Number(raw.replace(/,/g, ''))
  if (Number.isFinite(number)) {
    return (
      'PHP ' + number.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
    )
  }
  return raw
}

/** Words in the abstract: whitespace-separated tokens (mirrors the backend count). */
export function abstractWordCount(value) {
  const trimmed = text(value).trim()
  return trimmed === '' ? 0 : trimmed.split(/\s+/).length
}

/**
 * The paragraphs of a narrative field, as the document prints them: blank lines separate
 * paragraphs and single line breaks are kept inside a paragraph. Nothing is added or
 * reworded.
 */
export function textParagraphs(value) {
  return text(value)
    .split(/\n\s*\n/)
    .map((paragraph) => paragraph.trim())
    .filter((paragraph) => paragraph !== '')
}

/**
 * The members of the project team, one per line. The field is a multiline input ("one author
 * per line"), so the members are split on line breaks only - never on spaces or commas, so a
 * name like "Bagares, Xarzha Maurine" stays a single member. Blank lines are skipped, and a
 * value saved as one line is returned as exactly one member.
 */
export function projectTeamMembers(value) {
  return text(value)
    .split(/\r\n|\r|\n/)
    .map((line) => line.trim())
    .filter((line) => line !== '')
}

/**
 * Mirrors the backend submission gate: the report can be submitted once the report title,
 * the abstract, the introduction and the results and discussion are present. Everything
 * else is optional, exactly as in the printed format.
 */
export function hasTerminalReportContent(report) {
  return (
    hasText(report?.projectTitle) &&
    hasText(report?.abstractText) &&
    sectionHasText(report?.introduction) &&
    sectionHasText(report?.resultsAndDiscussion)
  )
}

/**
 * True when the report holds anything at all. Used by the proponent's own list to offer the
 * document view for a draft that is still being filled in.
 */
export function hasAnyTerminalContent(report) {
  if (!report || typeof report !== 'object') return false
  return Object.entries(report).some(([key, value]) => {
    if (key === 'summaryRows') return listOf(value).some(summaryRowHasValue)
    if (Array.isArray(value)) return listOf(value).some(rowHasContent)
    if (value && typeof value === 'object') {
      return sectionHasText(value) || listOf(value.tables).some(tableHasContent)
    }
    return hasText(value)
  })
}


/**
 * The errors of the report, keyed by field, plus a one-line summary.
 *
 * `forSubmission` applies the submission rules - the required core sections and the
 * one-page abstract limit. A draft may be saved while the report is still incomplete,
 * exactly like the other reporting stages; the abstract counter is always available to the
 * form, so the proponent sees the limit while typing.
 */
export function terminalReportValidation(report, { forSubmission = false } = {}) {
  const errors = {}
  if (!forSubmission) {
    return { errors, summary: '' }
  }

  if (!hasText(report?.projectTitle)) {
    errors.projectTitle = 'Project Title is required.'
  }
  for (const field of TERMINAL_NARRATIVE_FIELDS) {
    if (field.required && !hasText(report?.[field.key])) {
      errors[field.key] = `${field.label.replace(/^[A-Z\s/]+/, (match) => match.trim())} is required.`
    }
  }
  for (const section of TERMINAL_BODY_SECTIONS) {
    if (section.kind !== 'text') continue
    if (!section.required) continue
    if (!sectionHasText(report?.[section.key])) {
      errors[section.key] = `Section ${section.number} (${section.title}) is required.`
    }
  }
  const words = abstractWordCount(report?.abstractText)
  if (words > MAX_ABSTRACT_WORDS) {
    errors.abstractText = `The abstract must not exceed ${MAX_ABSTRACT_WORDS} words (currently ${words} words). Please shorten it before submitting.`
  }

  return {
    errors,
    summary: Object.keys(errors).length
      ? 'Please complete the required sections before submitting the Terminal Report.'
      : '',
  }
}

/**
 * The step of the form that owns a field or a section, so a blocked submission opens the
 * step where the missing information is.
 */
export function terminalSectionOf(key) {
  for (const section of TERMINAL_SECTIONS) {
    if (section.key === key) return key
    if (section.sheets.includes(key)) return section.key
  }
  if (TERMINAL_COVER_FIELDS.some((field) => field.key === key)) return 'cover'
  if (TERMINAL_NARRATIVE_FIELDS.some((field) => field.key === key)) return 'preliminary'
  if (TERMINAL_FINANCIAL_FIELDS.some((field) => field.key === key)) return 'summary'
  // The table of contents and the lists are all edited in the same step of the form.
  if (TERMINAL_LISTS.some((list) => list.key === key)) return 'contents'
  return null
}

/**
 * The cover values the format requires. The completion indicator turns on only when every one
 * of them carries a value, so the project title that RPIS fills in from the project record is
 * never enough on its own.
 */
function requiredCoverFields() {
  return TERMINAL_COVER_FIELDS.filter((field) => field.required)
}

/** The narrative fields the format requires (the abstract). */
function requiredNarrativeFields() {
  return TERMINAL_NARRATIVE_FIELDS.filter((field) => field.required)
}

/**
 * The summary rows only the proponent can fill. The other rows of the Project Information
 * Details table are pre-filled from the project record, so a summary that still holds only
 * those pre-filled rows is not complete.
 */
const SUMMARY_ENTERED_LABELS = new Set([
  'Base Station',
  'Area Covered',
  'Data Collection',
  'Production Comparison',
])

/** True when the proponent has entered something of their own on the summary sheet. */
function summaryHasOwnContent(report) {
  return (
    TERMINAL_FINANCIAL_FIELDS.some((field) => hasText(report[field.key])) ||
    listOf(report.summaryObjectives).some(rowHasContent) ||
    listOf(report.summaryRows).some(
      (row) => SUMMARY_ENTERED_LABELS.has(text(row?.label).trim()) && summaryRowHasValue(row)
    ) ||
    hasText(report.summaryAccomplishmentsTitle)
  )
}

/**
 * True when a step of the form is complete: every part the format requires is present and
 * passes validation. A step is never complete merely because it was opened or saved, and a
 * value that only the project record supplied (the pre-filled cover title, the pre-filled
 * summary rows) never completes a step on its own. Optional entries never block completion.
 */
export function terminalSectionFilled(report, sectionKey) {
  if (!report) return false
  const section = TERMINAL_SECTIONS.find((entry) => entry.key === sectionKey)
  if (!section) return false

  return section.sheets.some((sheet) => {
    if (sheet === 'cover') {
      // Every required cover value, including the manually entered Project Team, must be
      // present. The pre-filled project title alone is not enough.
      return requiredCoverFields().every((field) => hasText(report[field.key]))
    }
    if (sheet === 'summary') {
      return summaryHasOwnContent(report)
    }
    if (sheet === 'acknowledgment' || sheet === 'abstract') {
      // The abstract is required; the keywords and the acknowledgment are optional.
      const required = requiredNarrativeFields()
      return required.length > 0 && required.every((field) => hasText(report[field.key]))
    }
    if (sheet === 'contents') {
      return listOf(report.tableOfContents).some(rowHasContent)
    }
    if (TERMINAL_LISTS.some((list) => list.key === sheet)) {
      return listOf(report[sheet]).some(rowHasContent)
    }
    if (sheet === 'literatureCited') return listOf(report.literatureCited).some(rowHasContent)
    if (sheet === 'appendix') {
      return (
        listOf(report.appendices).some(rowHasContent) ||
        listOf(report.appendixTables).some(tableHasContent)
      )
    }
    const bodySection = TERMINAL_BODY_SECTIONS.find((entry) => entry.key === sheet)
    if (bodySection?.required) {
      // A required section must hold text; a table on its own does not satisfy the validation.
      return sectionHasText(report[sheet])
    }
    const value = report[sheet]
    return sectionHasText(value) || listOf(value?.tables).some(tableHasContent)
  })
}

/**
 * One reference of "Literature Cited" as a single line, built only from the fields the
 * proponent entered: author, year, title, edition, place of publication, journal or
 * publication name and page number. Missing parts are skipped - no bibliographic
 * information is ever generated.
 */
export function referenceLine(reference) {
  const author = text(reference?.author).trim()
  const year = text(reference?.year).trim()
  const parts = []
  if (author) parts.push(year ? `${author} (${year})` : author)
  else if (year) parts.push(`(${year})`)
  if (hasText(reference?.title)) parts.push(text(reference.title).trim())
  if (hasText(reference?.edition)) parts.push(text(reference.edition).trim())
  if (hasText(reference?.place)) parts.push(text(reference.place).trim())
  const journal = text(reference?.journal).trim()
  const pages = text(reference?.pages).trim()
  if (journal) parts.push(pages ? `${journal}, ${pages}` : journal)
  else if (pages) parts.push(pages)
  if (!parts.length) return ''
  const line = parts.join('. ')
  // The proponent's own punctuation is preserved: a period is only added when the line
  // does not already end with one.
  return line.endsWith('.') ? line : `${line}.`
}


/**
 * The captioned tables of the body, grouped by section, with the number printed above each
 * one ("Table 1", "Table 2", ...). The number is generated from the position of the table
 * in the document, so nothing is stored and the numbering can never disagree with the
 * document.
 */
export function bodyTableNumbers(report) {
  const result = {}
  let number = 1
  for (const section of TERMINAL_BODY_SECTIONS) {
    if (section.kind !== 'text') continue
    const tables = listOf(report?.[section.key]?.tables).filter(tableHasContent)
    if (!tables.length) continue
    result[section.key] = tables.map((table) => ({ table, number: String(number++) }))
  }
  return result
}

/** The tables of the appendix, numbered "A1", "A2", ... in document order. */
export function appendixTableNumbers(report) {
  return listOf(report?.appendixTables)
    .filter(tableHasContent)
    .map((table, index) => ({ table, number: `A${index + 1}` }))
}

/** The numbered subsections of a body section: heading plus the number the document uses. */
export function sectionSubsectionNumbers(section, sectionNumber) {
  return listOf(section?.subsections)
    .filter((subsection) => hasText(subsection?.text))
    .map((subsection, index) => ({
      subsection,
      number: `${sectionNumber}.${index + 1}`,
    }))
}

/** The appendix entries that hold something, with the number the document prints. */
export function appendixNumbers(report) {
  return listOf(report?.appendices)
    .filter(rowHasContent)
    .map((appendix, index) => ({ appendix, number: index + 1 }))
}

