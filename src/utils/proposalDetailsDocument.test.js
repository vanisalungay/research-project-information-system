/**
 * proposalDetailsDocument.test.js
 * ---------------------------------------------------------------------------
 * The OC "Download Proposal Details" document is composed as HTML and printed
 * through the shared client-side pipeline. The renderer imports the MSU-Naawan
 * seal with a Vite `?inline` query, which Node cannot resolve, so its assembly is
 * guarded at the source level - the technique officialProposalForm.test.js uses.
 *
 * The checks below pin down what the requirement promises: the document is a
 * complete print document, it reuses the official form renderer, it reports the
 * proposal's own evaluation/approval/status data (never a placeholder), it
 * escapes that data, and a draft is not presented as an issued Special Order.
 *
 * Run with: npm test
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const read = (path) => readFileSync(fileURLToPath(new URL(path, import.meta.url)), 'utf8')

const DOCUMENT = read('./proposalDetailsDocument.js')
const OFFICIAL = read('./officialProposalForm.js')
const EXPORT = read('./documentExport.js')

test('the document reuses the shared PDF pipeline and official form', () => {
  assert.match(DOCUMENT, /import \{ savePdfDocument \} from '@\/utils\/documentExport'/,
    'the shared PDF helper must be reused, not reimplemented')
  assert.match(
    DOCUMENT,
    /import \{ OFFICIAL_FORM_STYLES, renderOfficialProposalForm \} from '@\/utils\/officialProposalForm'/,
    'the official form renderer and its styles must be reused',
  )
  assert.match(OFFICIAL, /export function renderOfficialProposalForm/, 'the renderer must still exist')
  assert.match(DOCUMENT, /renderOfficialProposalForm\(officialProposal\)/,
    'the downloaded document must contain the official Full-Blown R&D Proposal form')
  assert.match(DOCUMENT, /OFFICIAL_FORM_STYLES\}\$\{DETAILS_COVER_STYLES\}/,
    'the official print styles and the cover styles must share one stylesheet')
  assert.ok(!DOCUMENT.includes('printDocument'),
    'the proposal download must not use the browser print dialog, which adds its own header/footer')
})

test('the generated file is a complete, standalone document', () => {
  assert.ok(DOCUMENT.includes('<!doctype html>'), 'the file must declare a doctype')
  assert.ok(DOCUMENT.includes('<title>${esc(title)}</title>'), 'the document needs its own title')
  assert.match(DOCUMENT, /<section class="oc-official">/, 'the official form starts a new page as a section')
  assert.match(DOCUMENT, /section\.oc-official \{[^}]*break-before: page/, 'the section must break in print')
  assert.match(DOCUMENT, /section\.oc-official \{[^}]*page-break-before: always/, 'and in older engines')
  assert.ok(!DOCUMENT.includes('oc-page-break'), 'an empty spacer element must not print a blank page')
  assert.ok(!DOCUMENT.includes('oc-official-start'), 'no extra padding is added on top of the page margins')
  assert.match(DOCUMENT, /savePdfDocument\(\{/, 'the download must go through the shared PDF helper')
})

test('the page numbers are generated by the document at the bottom-right, not by the browser', () => {
  const pageRule = OFFICIAL.slice(OFFICIAL.indexOf('@page {'), OFFICIAL.indexOf('* { box-sizing'))
  assert.ok(pageRule.length > 0, 'the stylesheet must define @page')
  assert.match(pageRule, /margin: 9mm 13mm 9mm;/, 'the page margins stay the document\'s own')
  assert.match(pageRule, /@bottom-right \{/, 'the page number must sit in the bottom-right margin box')
  assert.ok(!pageRule.includes('@bottom-center'), 'the page number must never be centred')
  assert.match(pageRule, /content: "Page " counter\(page\) " of " counter\(pages\)/,
    'the numbering must be the document\'s own sequential counter')
})

test('the document carries no generated timestamp or browser metadata', () => {
  assert.ok(!DOCUMENT.includes('Generated:'), 'a download timestamp is browser metadata, not record data')
  assert.ok(!DOCUMENT.includes('new Date().toISOString()'), 'the builder must not inject a timestamp')
  assert.ok(!DOCUMENT.includes('localhost'), 'no URL may be written into the document')
  assert.ok(!DOCUMENT.includes('window.location'), 'no application route may be written into the document')
})

test('the cover table has one label column and one value column', () => {
  assert.match(DOCUMENT, /function row\(label, value\) \{\s*return `<tr><th>\$\{esc\(label\)\}<\/th><td>\$\{value\}<\/td><\/tr>`/,
    'a row must emit exactly one label cell and one value cell')
  assert.match(DOCUMENT, /colgroup><col class="oc-col-label" \/><col \/><\/colgroup>/,
    'the cover table must declare two columns - the old four-column declaration left half of every row empty')
  assert.ok(!DOCUMENT.includes(', true)'), 'the removed wide/colspan row variant must not return')
})

test('the header is the same for every role', () => {
  assert.ok(DOCUMENT.includes('RESEARCH PROJECT INFORMATION SYSTEM'), 'the role-neutral office line is printed')
  assert.ok(!DOCUMENT.includes('OFFICE OF THE CHANCELLOR'), 'the document must not identify the viewer role')
  assert.ok(DOCUMENT.includes('PROPOSAL DETAILS'), 'the document title stays')
})

test('the cover reports every part of the proposal the request lists', () => {
  for (const heading of [
    '1. Project and Proponent Information',
    '2. Research Details',
    '3. Proposal Description',
    '4. Evaluation, Approval and Special Order',
    '5. Office of the Chancellor',
    '6. Current Project Status',
  ]) {
    assert.ok(DOCUMENT.includes(heading), `the "${heading}" section must be rendered`)
  }

  for (const field of [
    'proposal.projectTitle',
    'proposal.proponent?.name',
    'proposal.college',
    'proposal.researchType',
    'proposal.startDate',
    'proposal.personnel',
    'proposal.executiveSummary',
    'proposal.objectivesGeneral',
    'proposal.methodology',
    'review.decision',
    'review.overallComments',
    'proposal.soNumber',
    'proposal.soUploadedAt',
    'proposal.needsBudget',
    'proposal.remarks',
    'proposalStatusLabel(proposal.status)',
  ]) {
    assert.ok(DOCUMENT.includes(field), `the document must read ${field} from the record`)
  }
})

test('evaluation values come from the shared score arithmetic', () => {
  assert.match(DOCUMENT, /import \{ REVIEW_GROUPS, groupAverage, reviewWeightedScore \}/,
    'the score helpers must come from reviewScores.js')
  assert.ok(DOCUMENT.includes('reviewWeightedScore(review)'), 'the overall weighted score must be printed')
  assert.ok(DOCUMENT.includes('No evaluation reviews recorded.'), 'an empty evaluation must say so')
})

test('proposal text is escaped before it reaches the document', () => {
  assert.match(DOCUMENT, /function esc\(value\)/, 'the renderer must define an escaper')
  assert.ok(DOCUMENT.includes(".replace(/&/g, '&amp;')"), 'markup characters must be escaped')
  assert.ok(DOCUMENT.includes('return esc(content).replace(/\\r?\\n/g, \'<br />\')'),
    'multi-line values must be escaped then line-broken')
})

test('a draft Special Order is labelled and never printed as issued', () => {
  assert.match(DOCUMENT, /import \{ isSoDraft, soDraftFileLabel \} from '@\/utils\/soDraft'/,
    'draft detection must reuse the shared helper')
  assert.ok(DOCUMENT.includes('DRAFT &mdash; not yet issued'), 'the draft state must be visible on the cover')
  assert.ok(
    DOCUMENT.includes("const officialProposal = isSoDraft(p) ? { ...p, soFileName: null } : p"),
    'a draft document must not be listed as an issued SO attachment in the official form',
  )
  assert.ok(DOCUMENT.includes('is still awaiting the Chancellor'), 'the draft note must explain the state')
})

test('the download action saves a server-rendered PDF file', () => {
  assert.match(DOCUMENT, /export function downloadProposalDetails\(/, 'the pure render entry point must exist')
  assert.match(DOCUMENT, /return savePdfDocument\(\{[\s\S]*html: buildProposalDetailsHtml\(/,
    'the entry point must send the generated document to the shared PDF renderer')
  assert.match(DOCUMENT, /filename: `Proposal Details - \$\{project\}\.pdf`/,
    'the saved file must be named after the proposal')
})

test('the shared PDF helper renders on the server and downloads a Blob', () => {
  assert.match(EXPORT, /export async function savePdfDocument\(/,
    'one helper must serve every document download')
  assert.match(EXPORT, /api\.post\(\s*'\/api\/documents\/pdf'/, 'the PDF is rendered by the backend')
  assert.match(EXPORT, /responseType: 'blob'/, 'the response is the PDF file itself')
  assert.match(EXPORT, /link\.download = documentFileName\(/,
    'the Blob is handed to the browser as a sanitised, named download')
  assert.ok(!EXPORT.includes('displayHeaderFooter'), 'no browser print header/footer option may be needed')
  const saveSource = EXPORT.slice(
    EXPORT.indexOf('export async function savePdfDocument'),
    EXPORT.indexOf('// ===== Proposal document builder'),
  )
  assert.ok(!saveSource.includes('win.print()'), 'the PDF path must never open the print dialog')
})

test('the shared role entry point re-reads a saved record and never fetches an unsaved one', () => {
  assert.match(DOCUMENT, /export async function downloadProposalRecord\(/, 'one entry point serves every role')
  const start = DOCUMENT.indexOf('export async function downloadProposalRecord(')
  const source = DOCUMENT.slice(start)
  assert.ok(source.includes('api.get(`/api/proposals/${id}`)'), 'a saved proposal is re-read by id')
  assert.ok(source.includes('api.get(`/api/proposals/${id}/reviews`)'), 'its reviews are re-read by id')
  assert.ok(source.includes('generatedAt'), 'the option is still accepted for API compatibility')
  assert.ok(source.includes('if (id != null)'), 'the fetch happens only when an id is supplied')
  assert.ok(source.includes('downloadProposalDetails({'), 'the fetched/in-memory record is printed')
})

test('the approval block prints only what the record actually holds', () => {
  const start = DOCUMENT.indexOf('function approvalSection(')
  const source = DOCUMENT.slice(start, DOCUMENT.indexOf('function statusSection('))
  assert.ok(source.includes('No Special Order recorded yet.'), 'an untransacted proposal says so')
  assert.ok(source.includes('if (draft || soNumber)'), 'the SO number row appears only with data')
  assert.ok(source.includes('if (budget)'), 'the budget routing row appears only with a decision')
  assert.ok(source.includes('if (text(proposal.remarks))'), 'notes print only when recorded')
  assert.ok(source.includes('if (text(soDocument))'), 'the SO document row appears only with a document')
})
