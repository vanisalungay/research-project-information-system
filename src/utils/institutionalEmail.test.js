/**
 * institutionalEmail.test.js
 * ---------------------------------------------------------------------------
 * Verifies the institution's address rule for administrator-created accounts.
 *
 * The administrator never types an address, so the rule has to be right: the given names run
 * together, the surname follows one dot, nothing but a-z0-9 survives, and a clash is
 * resolved with a number rather than by reusing someone else's address.
 *
 * Run with: npm test
 */
import test from 'node:test'
import assert from 'node:assert/strict'

import {
  INSTITUTIONAL_EMAIL_DOMAIN,
  availableInstitutionalEmail,
  institutionalEmail,
  institutionalEmailLocalPart,
  normalizeEmailInput,
  normalizeEmailPart,
  personNameParts,
} from './institutionalEmail.js'

test('the one institutional domain is the corrected university domain', () => {
  assert.equal(INSTITUTIONAL_EMAIL_DOMAIN, '@msunaawan.edu.ph')
  // The previous misspelling must never be generated by the shared rule.
  assert.ok(!institutionalEmail('Jane Doe').endsWith('@msunawaan.edu.ph'))
})

test('the given names run together and the surname follows one dot', () => {
  assert.equal(institutionalEmail('Xarzha Maurine Bagares'), 'xarzhamaurine.bagares@msunaawan.edu.ph')
  assert.equal(institutionalEmail('Jane Doe'), 'jane.doe@msunaawan.edu.ph')
  assert.equal(institutionalEmail('Ana Maria Clara Reyes'), 'anamariaclara.reyes@msunaawan.edu.ph')
  // A single name is used as it is.
  assert.equal(institutionalEmail('Madonna'), 'madonna@msunaawan.edu.ph')
})

test('the address never contains a space', () => {
  for (const name of ['Xarzha Maurine Bagares', '  Jane   Doe  ', 'Juan Dela Cruz']) {
    assert.ok(!institutionalEmail(name).includes(' '), name + ' must produce a space-free address')
  }
})

test('case, accents and punctuation are normalized away', () => {
  assert.equal(normalizeEmailPart('  Bañares '), 'banares')
  assert.equal(institutionalEmail('MARÍA Bañares'), 'maria.banares@msunaawan.edu.ph')
  assert.equal(institutionalEmail("René O'Brien"), 'rene.obrien@msunaawan.edu.ph')
  assert.equal(institutionalEmail('Ana-Maria Reyes'), 'anamaria.reyes@msunaawan.edu.ph')
})

test('the standard Last, First order derives the same address', () => {
  // The form asks for "Dela Cruz, Juan, M., Jr." - the address still uses the
  // given names first and the whole surname second.
  assert.equal(institutionalEmail('Dela Cruz, Juan'), 'juan.delacruz@msunaawan.edu.ph')
  assert.equal(
    institutionalEmail('Dela Cruz, Juan, M., Jr.'),
    'juanm.delacruz@msunaawan.edu.ph',
  )
  assert.equal(
    institutionalEmail('Bagares, Xarzha Maurine'),
    'xarzhamaurine.bagares@msunaawan.edu.ph',
  )
  assert.equal(
    institutionalEmail('De La Cruz, Maria Clara, M.'),
    'mariaclaram.delacruz@msunaawan.edu.ph',
  )
})

test('both name orders resolve to the same given names and surname', () => {
  assert.deepEqual(personNameParts('Dela Cruz, Juan, M., Jr.'), {
    given: ['Juan', 'M.'],
    surname: ['Dela', 'Cruz'],
  })
  // With the middle initial omitted, the third component is the suffix.
  assert.deepEqual(personNameParts('Dela Cruz, Juan, Jr.'), {
    given: ['Juan'],
    surname: ['Dela', 'Cruz'],
  })
  // The Dean form's plain order: the surname particles keep "Dela Cruz" whole.
  assert.deepEqual(personNameParts('Juan Dela Cruz'), {
    given: ['Juan'],
    surname: ['Dela', 'Cruz'],
  })
  assert.deepEqual(personNameParts('Maria Clara Dela Cruz'), {
    given: ['Maria', 'Clara'],
    surname: ['Dela', 'Cruz'],
  })
  // The two orders derive the same address.
  assert.equal(institutionalEmail('Juan Dela Cruz'), 'juan.delacruz@msunaawan.edu.ph')
  assert.equal(institutionalEmail('JUAN DELA CRUZ'), 'juan.delacruz@msunaawan.edu.ph')
  assert.equal(
    institutionalEmail('Juan Dela Cruz'),
    institutionalEmail('Dela Cruz, Juan'),
  )
})

test('a name with nothing usable yields no address', () => {
  assert.equal(institutionalEmail(''), '')
  assert.equal(institutionalEmail('   '), '')
  assert.equal(institutionalEmail('***'), '')
  assert.equal(institutionalEmail(null), '')
  assert.equal(institutionalEmailLocalPart(''), '')
})

test('a typed and a pasted address normalize to the same value', () => {
  // Auto-capitalization and a stray trailing space are what made the same address fail
  // when typed but work when pasted.
  assert.equal(
    normalizeEmailInput('  Vanisa.Lungay@MSUNAAWAN.EDU.PH '),
    'vanisa.lungay@msunaawan.edu.ph',
  )
  // A non-breaking space from the account table and zero-width characters are invisible.
  assert.equal(
    normalizeEmailInput(' vanisa.lungay@msunaawan.edu.ph​'),
    'vanisa.lungay@msunaawan.edu.ph',
  )
  // Valid characters inside the address are never rewritten.
  assert.equal(
    normalizeEmailInput('first.last+tag@msunaawan.edu.ph'),
    'first.last+tag@msunaawan.edu.ph',
  )
  assert.equal(normalizeEmailInput(null), '')
})

test('a taken address is numbered before the domain', () => {
  const taken = ['xarzhamaurine.bagares@msunaawan.edu.ph']

  const first = availableInstitutionalEmail('Xarzha Maurine Bagares', taken)
  assert.equal(first.email, 'xarzhamaurine.bagares2@msunaawan.edu.ph')
  assert.equal(first.suffix, 2)
  assert.equal(first.adjusted, true)

  // And it keeps counting while the numbered ones are taken too.
  const next = availableInstitutionalEmail('Xarzha Maurine Bagares', [...taken, first.email])
  assert.equal(next.email, 'xarzhamaurine.bagares3@msunaawan.edu.ph')
})

test('a free address is used unchanged', () => {
  const result = availableInstitutionalEmail('Jane Doe', ['someone.else@msunaawan.edu.ph'])
  assert.equal(result.email, 'jane.doe@msunaawan.edu.ph')
  assert.equal(result.suffix, 1)
  assert.equal(result.adjusted, false)
  assert.ok(result.email.endsWith(INSTITUTIONAL_EMAIL_DOMAIN))
})