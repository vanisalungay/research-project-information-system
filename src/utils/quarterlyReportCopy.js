/**
 * quarterlyReportCopy.js
 * ---------------------------------------------------------------------------
 * What a "Create a Copy" carries from a previous Quarterly Progress Report into the next
 * one.
 *
 * Copying never duplicates a report: it only supplies starting values for the existing
 * Create Quarterly Report workflow, which still creates its own draft with its own
 * identifier and its own reporting period (the backend derives the next required stage
 * from the project's own submitted reports).
 *
 * The source report and the destination form share the same structure, so the copy is an
 * EXCLUDE-list copy: every field of the source report travels except the system-managed
 * ones listed in EXCLUDED_REPORT_FIELDS. An eligible field can therefore never be dropped
 * merely because it is not named here:
 *
 *   identification      projectTitle, projectLeader, leaderGender, baseStation,
 *                       sitesOfImplementation, projectDuration, projectStartDate,
 *                       projectEndDate
 *   narratives          catchUpPlan, problemsConcerns, suggestedSolutions
 *   objectives table    objective, target, actual, percentagePeriod,
 *                       percentageCumulative (every row, every column)
 *   6Ps outputs table   outputType, expectedOutput, actualOutput (every row)
 *   Project Workplan    asOf, projectTitle, projectLeader, projectDuration,
 *                       objectives (objective + twelve monthly cells + total), remarks
 *
 * Excluded because they belong to the source report or are regenerated by the workflow:
 * the identifier, the proposal link, the reporting period and year, the report type, the
 * status, the audit and submission metadata, the uploaded document references, and the
 * reference to the report the copy was started from.
 *
 * Nested objects and arrays are deep-copied, so editing the new report can never change
 * the original one.
 *
 * Run the rules with: npm test
 */

/**
 * Fields that must never travel: they are system-managed, belong to the source report
 * alone, or are regenerated when the new report is saved.
 */
export const EXCLUDED_REPORT_FIELDS = [
  // Identity and reporting stage: the new report gets its own.
  'id',
  'proposalId',
  'period',
  'year',
  'reportType',
  'status',
  // Audit and submission metadata.
  'createdBy',
  'createdAt',
  'updatedAt',
  'submittedBy',
  'submittedAt',
  // Attachments: a new report attaches its own files.
  'workplanFileName',
  'workplanFilePath',
  'terminalReportFileName',
  'terminalReportFilePath',
  // Recorded by the new save, never inherited from the source report.
  'copiedFromReportId',
]

/** Fields of one objective row: the whole repeated row is editable report content. */
export const OBJECTIVE_FIELDS = [
  'objective',
  'target',
  'actual',
  'percentagePeriod',
  'percentageCumulative',
]

/** Fields of one 6Ps output row. */
export const OUTPUT_FIELDS = ['outputType', 'expectedOutput', 'actualOutput']

/** Header and narrative fields of the Project Workplan. */
export const WORKPLAN_FIELDS = [
  'asOf',
  'projectTitle',
  'projectLeader',
  'projectDuration',
  'remarks',
]

/** Fields of one Project Workplan objective row (plus its month cells). */
export const WORKPLAN_OBJECTIVE_FIELDS = ['objective', 'months', 'total']

/** Number of month columns of the Project Workplan (mirrors ProjectWorkplanForm). */
export const WORKPLAN_MONTHS = 12

/** The report id in a `?copyFrom=` query value, or null when there is none/unusable. */
export function copySourceId(value) {
  if (value === null || value === undefined || value === '') return null
  const id = Number(value)
  return Number.isInteger(id) && id > 0 ? id : null
}

function text(value) {
  if (value === null || value === undefined) return ''
  return typeof value === 'string' ? value : String(value)
}

function hasText(value) {
  return text(value).trim() !== ''
}

function listOf(value) {
  return Array.isArray(value) ? value : []
}

/**
 * True when a value carries content. 0, false and non-empty arrays/objects count as
 * content, so a valid value is never mistaken for an empty one.
 */
function hasContent(value) {
  if (value === null || value === undefined) return false
  if (typeof value === 'string') return value.trim() !== ''
  if (Array.isArray(value)) return value.length > 0
  if (typeof value === 'object') return Object.keys(value).length > 0
  return true
}

/**
 * A deep copy of any nested structure. The report payload holds plain JSON structures
 * (rows, arrays, the workplan), so serializing it detaches the copy from the source
 * report: editing the new draft can never reach back into the original report.
 */
function deepCopy(value) {
  if (value === null || typeof value !== 'object') return value
  return JSON.parse(JSON.stringify(value))
}

/**
 * One copied row: every field of the row is editable report content, so the whole row
 * travels (the destination form has a field for each of them). Text columns are
 * normalised to strings; a valid 0/false is preserved as its text form.
 */
function copyRow(row, fields) {
  const copy = { ...(row && typeof row === 'object' ? row : {}) }
  for (const field of fields) copy[field] = text(copy[field])
  return copy
}

/**
 * The objective rows of the new report - the objectives, their targets, the reported
 * accomplishments (actual) and both percentages.
 *
 * `fillEmptyOnly` is used when the target is a draft that already exists: a draft which
 * already describes its own objective is never replaced (the proponent's saved work
 * wins), while a draft without a plan yet starts from the previous report's rows.
 */
function copyObjectives(source, target, fillEmptyOnly) {
  const targetRows = listOf(target?.objectives)
  const rows = listOf(source?.objectives)
    .map((row) => copyRow(row, OBJECTIVE_FIELDS))
    .filter((row) => OBJECTIVE_FIELDS.some((field) => hasText(row[field])))

  if (!rows.length) return targetRows
  if (fillEmptyOnly && targetRows.some((row) => hasText(row?.objective))) return targetRows
  return rows
}

/** The 6Ps rows of the new report: the expected output and the reported actual output. */
function copyOutputs(source, target, fillEmptyOnly) {
  const targetRows = listOf(target?.outputs)
  const filled = targetRows.some(
    (row) => hasText(row?.expectedOutput) || hasText(row?.actualOutput),
  )
  if (fillEmptyOnly && filled) return targetRows

  const rows = listOf(source?.outputs)
    .map((row) => copyRow(row, OUTPUT_FIELDS))
    .filter((row) => OUTPUT_FIELDS.some((field) => hasText(row[field])))
  return rows.length ? rows : targetRows
}

/**
 * The starting values of the new report: every source field except the excluded ones,
 * laid over the values the existing workflow already prepared in `target` (the next
 * required reporting period and report type, the project header from the proposal, an
 * existing draft's content).
 *
 * With `fillEmptyOnly` (continuing an existing draft) a field the target already carries
 * is kept, so the copy only fills in what the draft is still missing.
 */
export function copyReportValues(source, target = {}, { fillEmptyOnly = false } = {}) {
  const result = { ...(target && typeof target === 'object' ? target : {}) }
  if (!source || typeof source !== 'object') return result

  for (const [field, value] of Object.entries(source)) {
    if (EXCLUDED_REPORT_FIELDS.includes(field)) continue

    if (field === 'objectives') {
      result.objectives = copyObjectives(source, target, fillEmptyOnly)
      continue
    }
    if (field === 'outputs') {
      result.outputs = copyOutputs(source, target, fillEmptyOnly)
      continue
    }
    if (field === 'workplan') {
      // The structured workplan is deep-copied through its own rules, so the new report
      // never shares its rows or month cells with the source report.
      result.workplan = copyWorkplanValues(value, target?.workplan, { fillEmptyOnly })
      continue
    }

    if (!hasContent(value)) continue
    if (fillEmptyOnly && hasContent(result[field])) continue
    // Any nested structure is deep-copied rather than shared with the source report.
    result[field] = deepCopy(value)
  }
  return result
}

/** One copied workplan objective row: objective, its twelve month cells and the total. */
function copyWorkplanObjective(row) {
  const copy = copyRow(row, ['objective', 'total'])
  const months = listOf(row?.months)
    .slice(0, WORKPLAN_MONTHS)
    .map((month) => text(month))
  while (months.length < WORKPLAN_MONTHS) months.push('')
  copy.months = months
  return copy
}

/** True when a workplan row carries anything the proponent entered. */
function workplanRowHasContent(row) {
  return hasText(row.objective) || hasText(row.total) || row.months.some((month) => hasText(month))
}

/**
 * The Project Workplan of the new report: the "as of" reporting date, the workplan header,
 * the objective rows with their monthly target activities and totals, and the remarks.
 *
 * With `fillEmptyOnly` (continuing an existing draft) a workplan that already describes
 * its own objective is never replaced, and every value the draft already carries wins.
 */
export function copyWorkplanValues(source, target = {}, { fillEmptyOnly = false } = {}) {
  const result = { ...(target && typeof target === 'object' ? target : {}) }
  if (!source || typeof source !== 'object') return result

  for (const field of WORKPLAN_FIELDS) {
    if (!hasContent(source[field])) continue
    if (fillEmptyOnly && hasContent(result[field])) continue
    result[field] = text(source[field])
  }

  const targetRows = listOf(target?.objectives)
  const rows = listOf(source?.objectives).map(copyWorkplanObjective).filter(workplanRowHasContent)

  if (!rows.length) return result
  if (fillEmptyOnly && targetRows.some((row) => hasText(row?.objective))) return result
  result.objectives = rows
  return result
}
