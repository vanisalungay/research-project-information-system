/**
 * Notification type values shared by the list, the destination resolver and the
 * grouping rules.
 *
 * `ENDORSEMENT` means a Dean endorsement request. A proposal the RPS endorsed onward
 * to OVCRIGE is `PROPOSAL_ENDORSED`; historical rows written before that type existed
 * still carry `ENDORSEMENT` and are resolved by the recipient role.
 */
export const NOTIFICATION_TYPES = Object.freeze({
  PROPOSAL_UPDATE: 'PROPOSAL_UPDATE',
  REVIEW_REQUEST: 'REVIEW_REQUEST',
  APPROVAL: 'APPROVAL',
  REVISION: 'REVISION',
  REJECTION: 'REJECTION',
  FUNDING: 'FUNDING',
  ENDORSEMENT: 'ENDORSEMENT',
  PROPOSAL_ENDORSED: 'PROPOSAL_ENDORSED',
  PROPOSAL_ANNOUNCEMENT: 'PROPOSAL_ANNOUNCEMENT',
  QUARTERLY_REPORT: 'QUARTERLY_REPORT',
  PROJECT_COMPLETION: 'PROJECT_COMPLETION',
  DEAN_ASSIGNMENT: 'DEAN_ASSIGNMENT',
  SPECIAL_ORDER_DRAFT: 'SPECIAL_ORDER_DRAFT',
  REVISION_DEADLINE_REMINDER: 'REVISION_DEADLINE_REMINDER',
  EVALUATION_DEADLINE_REMINDER: 'EVALUATION_DEADLINE_REMINDER',
})

/** Types whose `proposalId` is a proposal id (not an endorsement request id). */
export const PROPOSAL_NOTIFICATION_TYPES = Object.freeze([
  NOTIFICATION_TYPES.PROPOSAL_UPDATE,
  NOTIFICATION_TYPES.REVIEW_REQUEST,
  NOTIFICATION_TYPES.APPROVAL,
  NOTIFICATION_TYPES.REVISION,
  NOTIFICATION_TYPES.REJECTION,
  NOTIFICATION_TYPES.FUNDING,
  NOTIFICATION_TYPES.PROPOSAL_ENDORSED,
  NOTIFICATION_TYPES.QUARTERLY_REPORT,
  NOTIFICATION_TYPES.PROJECT_COMPLETION,
  NOTIFICATION_TYPES.SPECIAL_ORDER_DRAFT,
  NOTIFICATION_TYPES.REVISION_DEADLINE_REMINDER,
  NOTIFICATION_TYPES.EVALUATION_DEADLINE_REMINDER,
])

/** True when the type is one of the proposal-workflow types. */
export function isProposalNotificationType(type) {
  return PROPOSAL_NOTIFICATION_TYPES.includes(String(type || '').toUpperCase())
}
