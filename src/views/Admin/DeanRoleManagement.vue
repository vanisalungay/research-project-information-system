<script setup>
/**
 * Dean Role Management (RPS ADMIN).
 *
 * Creating a Dean happens here, through the existing standard Create Account form opened
 * on the Dean role: the institutional email and the temporary password are generated by
 * the backend (`InstitutionalCredentialsService`) and shown once, so nothing about
 * account generation is duplicated. The list comes from the existing
 * `GET /api/users/deans`. There is no second implementation of the Dean rules and no new
 * endpoint.
 */
import { onMounted, ref } from 'vue'
import api from '@/utils/api'
import CreateUserModal from '@/views/Admin/CreateUserModal.vue'
import ReplaceDeanModal from '@/views/Admin/ReplaceDeanModal.vue'
import { statusTone } from '@/utils/statusTone.js'
import {
  accountStatusLabel,
  deanAssignmentStatusLabel,
} from '@/utils/statusCatalog.js'

const assignments = ref([])
const loading = ref(true)
const error = ref('')
const successMessage = ref('')

const filter = ref('ACTIVE')
const filters = [
  { value: 'ACTIVE', label: deanAssignmentStatusLabel('ACTIVE') },
  { value: 'REVOKED', label: deanAssignmentStatusLabel('REVOKED') },
  { value: 'ALL', label: 'All' },
]

const showCreateModal = ref(false)

const showDetails = ref(false)
const selected = ref(null)

const showManageModal = ref(false)
const selectedAssignment = ref(null)

/** Loads the appointment history for the selected filter. */
async function loadAssignments() {
  loading.value = true
  error.value = ''
  try {
    const response = await api.get('/api/users/deans/assignments', {
      params: { status: filter.value },
    })
    assignments.value = Array.isArray(response.data) ? response.data : []
  } catch (requestError) {
    console.error('Could not load the Dean assignments', requestError)
    error.value = 'The Dean assignments could not be loaded. Please try again.'
    assignments.value = []
  } finally {
    loading.value = false
  }
}

function setFilter(value) {
  filter.value = value
  loadAssignments()
}

/** Opens the account-creation form, already on the Dean role. */
function openCreate() {
  successMessage.value = ''
  showCreateModal.value = true
}

/**
 * A Dean account now exists: reload the list so it appears in the table at once, without
 * the administrator refreshing anything. The credentials stay on screen in the form.
 */
async function onDeanCreated() {
  successMessage.value =
    'The Dean account was created. Give the Dean the credentials shown above - the temporary password must be changed at first login.'
  await loadAssignments()
}

function openDetails(assignment) {
  selected.value = assignment
  showDetails.value = true
}

function closeDetails() {
  showDetails.value = false
  selected.value = null
}

/** Opens the replacement screen for the sitting Dean of this appointment. */
function openManage(assignment) {
  selectedAssignment.value = assignment
  showManageModal.value = true
}

function closeManage() {
  showManageModal.value = false
  selectedAssignment.value = null
}

async function onReplaced() {
  successMessage.value =
    'The Dean was replaced. The previous appointment is kept as history (REVOKED).'
  await loadAssignments()
}

function formatDate(value) {
  if (!value) return '—'
  const date = new Date(value)
  return Number.isNaN(date.getTime()) ? '—' : date.toLocaleDateString()
}

onMounted(loadAssignments)
</script>

