<template>
  <div class="tr-tables">
    <!-- Document view: each table with its generated number and caption, exactly as the
         official format prints it ("Table 1. <caption>"). -->
    <template v-if="readonly">
      <div v-for="entry in numbered" :key="entry.number" class="tr-table-block">
        <p class="tr-table-caption">
          Table {{ entry.number }}.{{ entry.table.caption ? ` ${entry.table.caption}` : '' }}
        </p>
        <table class="tr-grid">
          <thead>
            <tr>
              <th v-for="(column, index) in entry.table.columns" :key="index">{{ column }}</th>
            </tr>
          </thead>
          <tbody>
            <tr v-for="(row, rowIndex) in entry.table.rows" :key="rowIndex">
              <td v-for="(cell, cellIndex) in row" :key="cellIndex">{{ cell }}</td>
            </tr>
          </tbody>
        </table>
        <p v-if="entry.table.note" class="tr-table-note">{{ entry.table.note }}</p>
      </div>
    </template>

    <!-- Form: one editor per table, with its columns, rows and caption. -->
    <template v-else>
      <p v-if="hint" class="tr-hint">{{ hint }}</p>

      <div v-for="(table, tableIndex) in tables" :key="tableIndex" class="tr-table-editor">
        <div class="tr-entry-head">
          <span class="tr-entry-index">
            Table {{ tableIndex + 1 }} (the report numbers the tables it prints)
          </span>
          <button type="button" class="tr-btn tr-btn--remove" @click="removeTable(tableIndex)">
            Remove table
          </button>
        </div>

        <label class="tr-entry-field">
          <span class="tr-field-label">Caption</span>
          <input
            v-model="table.caption"
            type="text"
            class="tr-input"
            placeholder="e.g. Production and market indicators during the outbreak period"
          />
        </label>

        <div class="tr-table-scroll">
          <table class="tr-grid tr-grid--editor">
            <thead>
              <tr>
                <th v-for="(column, columnIndex) in table.columns" :key="columnIndex">
                  <div class="tr-column-head">
                    <input
                      v-model="table.columns[columnIndex]"
                      type="text"
                      class="tr-input tr-input--cell"
                    />
                    <button
                      type="button"
                      class="tr-btn-x"
                      :disabled="table.columns.length <= 1"
                      :aria-label="`Remove column ${columnIndex + 1}`"
                      @click="removeColumn(tableIndex, columnIndex)"
                    >
                      ×
                    </button>
                  </div>
                </th>
                <th class="tr-col-actions" aria-hidden="true"></th>
              </tr>
            </thead>
            <tbody>
              <tr v-for="(row, rowIndex) in table.rows" :key="rowIndex">
                <td v-for="(cell, cellIndex) in row" :key="cellIndex">
                  <input
                    v-model="table.rows[rowIndex][cellIndex]"
                    type="text"
                    class="tr-input tr-input--cell"
                  />
                </td>
                <td class="tr-col-actions">
                  <button
                    type="button"
                    class="tr-btn-x"
                    :aria-label="`Remove row ${rowIndex + 1}`"
                    @click="removeRow(tableIndex, rowIndex)"
                  >
                    ×
                  </button>
                </td>
              </tr>
            </tbody>
          </table>
        </div>

        <div class="tr-actions">
          <button type="button" class="tr-btn tr-btn--add" @click="addRow(tableIndex)">+ Add row</button>
          <button type="button" class="tr-btn" @click="addColumn(tableIndex)">+ Add column</button>
        </div>

        <label class="tr-entry-field">
          <span class="tr-field-label">Note under the table</span>
          <input v-model="table.note" type="text" class="tr-input" placeholder="Optional source note" />
        </label>
      </div>

      <p v-if="!tables.length" class="tr-empty">No tables yet.</p>

      <div class="tr-actions">
        <button type="button" class="tr-btn tr-btn--add" @click="addTable">+ Add table</button>
      </div>
    </template>
  </div>
</template>

<script setup>
import { TABLE_NEW_COLUMNS, TABLE_NEW_ROWS, emptyTable } from '@/utils/terminalReport'

/**
 * Tables of a Terminal Report body section (or of the appendix).
 *
 * The proponent enters the caption, the column headings and the cells - exactly the
 * structure the official format prints as "Table 1. <caption>" followed by a grid. The
 * table number is generated by the document from the position of the table, so it is never
 * typed by hand and never invented.
 *
 * Reviewers and the document viewer render the same tables read-only; a table without any
 * filled cell is not part of the report.
 */
const tables = defineModel({ type: Array, default: () => [] })

defineProps({
  /** Instruction shown above the tables while editing. */
  hint: { type: String, default: '' },
  /** [{ table, number }] used by the read-only document view. */
  numbered: { type: Array, default: () => [] },
  readonly: { type: Boolean, default: false },
})

function addTable() {
  const columns = Array.from({ length: TABLE_NEW_COLUMNS }, (_, index) => `Column ${index + 1}`)
  const table = emptyTable(columns)
  table.rows = Array.from({ length: TABLE_NEW_ROWS }, () => columns.map(() => ''))
  tables.value = [...(tables.value || []), table]
}

function removeTable(index) {
  tables.value = (tables.value || []).filter((_, i) => i !== index)
}

function addRow(tableIndex) {
  const table = tables.value[tableIndex]
  table.rows = [...table.rows, table.columns.map(() => '')]
}

function removeRow(tableIndex, rowIndex) {
  const table = tables.value[tableIndex]
  table.rows = table.rows.filter((_, i) => i !== rowIndex)
}

function addColumn(tableIndex) {
  const table = tables.value[tableIndex]
  table.columns = [...table.columns, `Column ${table.columns.length + 1}`]
  table.rows = table.rows.map((row) => [...row, ''])
}

function removeColumn(tableIndex, columnIndex) {
  const table = tables.value[tableIndex]
  if (table.columns.length <= 1) return
  table.columns = table.columns.filter((_, i) => i !== columnIndex)
  table.rows = table.rows.map((row) => row.filter((_, i) => i !== columnIndex))
}
</script>

