package com.rpis.backend.dto;

import lombok.Data;

/**
 * Administrative payload for creating the incoming Dean of an existing appointment and
 * completing the replacement in one step (Dean Role Management -> Manage Dean -> Replace
 * Dean).
 *
 * <p>The appointment being replaced is identified by {@link #assignmentId}, never by a
 * college typed into the browser: the sitting appointment's own college is what the new
 * Dean is appointed to. {@link #assignedCollege} is accepted only so the replacement form
 * can send the college it locked, and the service refuses a value that differs from the
 * appointment's college.
 *
 * <p>The institutional email and the temporary password are generated by the controller
 * (exactly as for every other administrator-created account) and are never accepted from
 * the client, so this payload cannot choose either.
 */
@Data
public class DeanReplacementCreateRequest {

    /** The ACTIVE appointment being replaced. Required. */
    private Long assignmentId;

    /** Full name of the incoming Dean. Required. */
    private String name;

    /** Designation / title. Blank = the outgoing appointment's designation. */
    private String designation;

    /**
     * The college the replacement form locked. When present it must equal the outgoing
     * appointment's college; blank means "use the appointment's college".
     */
    private String assignedCollege;
}
