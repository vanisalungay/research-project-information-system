package com.rpis.backend.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.InputStream;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Philippine administrative hierarchy used to validate the structured address of
 * the Create Proposal form ("Address *" section) on the server.
 * <p>
 * The form's dropdowns are built from the bundled PSGC extract in
 * {@code public/locations/ph}; the browser cannot be trusted to have used it, so
 * the same relationships ship with the backend as
 * {@code /locations/ph-address-catalog.json} (generated by
 * {@code scripts/build-backend-location-catalog.mjs} from that very extract) and
 * every submitted address is checked against them: a province of another region,
 * a city of another province, a district of another area or a country that does
 * not exist is rejected before the proposal is saved.
 * <p>
 * Barangays are not part of the catalog - the 42,046 records are only needed to
 * fill one dropdown and the client already loads them per region - so the parent
 * chain is verified down to the municipality / city while the barangay only has
 * to be present.
 * <p>
 * The catalog is loaded once per JVM, lazily and from the classpath. If the
 * resource cannot be read the checks that need it are skipped instead of blocking
 * every submission (see {@link ProposalService#validateAddressHierarchy}), so a
 * deployment mistake degrades to the previous behaviour rather than to a closed
 * door.
 */
public final class PhilippineAddressCatalog {

    private static final Logger log = LoggerFactory.getLogger(PhilippineAddressCatalog.class);

    /** Classpath location of the generated catalog. */
    static final String RESOURCE = "/locations/ph-address-catalog.json";

    /** The only country with a structured hierarchy. */
    public static final String PHILIPPINES = "Philippines";

    private static final Object LOCK = new Object();
    private static volatile PhilippineAddressCatalog shared;
    private static volatile boolean loadAttempted;

    /** One city or municipality, with the parents it actually belongs to. */
    private record City(String name, String regionCode, String provinceCode, String districtCode) {
    }

    private final Set<String> countries = new HashSet<>();
    /** Region name (and dropdown label) -> region code; keys are normalised. */
    private final Map<String, String> regionCodeByName = new HashMap<>();
    private final Map<String, String> regionNameByCode = new HashMap<>();
    /** {@code regionCode + "|" + province name} -> province code. */
    private final Map<String, String> provinceCodeByName = new HashMap<>();
    private final Map<String, String> provinceNameByCode = new HashMap<>();
    /** {@code regionCode + "|" + district name} -> district code. */
    private final Map<String, String> districtCodeByName = new HashMap<>();
    private final Map<String, String> districtNameByCode = new HashMap<>();
    private final Set<String> regionsWithProvinces = new HashSet<>();
    private final List<City> cities = new ArrayList<>();

    private PhilippineAddressCatalog() {
    }

    // ---------------------------------------------------------------- loading --

    /**
     * The catalog bundled with the application, or {@code null} when it cannot be
     * read (the caller then keeps the address checks that do not need it).
     */
    public static PhilippineAddressCatalog shared() {
        if (!loadAttempted) {
            synchronized (LOCK) {
                if (!loadAttempted) {
                    shared = loadFromClasspath();
                    loadAttempted = true;
                }
            }
        }
        return shared;
    }

    private static PhilippineAddressCatalog loadFromClasspath() {
        try (InputStream stream = PhilippineAddressCatalog.class.getResourceAsStream(RESOURCE)) {
            if (stream == null) {
                log.warn("Address catalog {} is missing from the classpath; the administrative "
                        + "hierarchy of a submitted address will not be verified.", RESOURCE);
                return null;
            }
            return fromJson(stream);
        } catch (Exception error) {
            log.warn("Address catalog {} could not be read ({}); the administrative hierarchy of a "
                    + "submitted address will not be verified.", RESOURCE, error.getMessage());
            return null;
        }
    }

    /** Reads a catalog from any stream - used by {@link #shared()} and by the tests. */
    static PhilippineAddressCatalog fromJson(InputStream stream) throws Exception {
        JsonNode root = new ObjectMapper().readTree(stream);
        PhilippineAddressCatalog catalog = new PhilippineAddressCatalog();

        for (JsonNode country : root.path("countries")) {
            catalog.countries.add(normalize(country.path("name").asText()));
        }
        for (JsonNode region : root.path("regions")) {
            String code = region.path("code").asText();
            String name = region.path("name").asText();
            String regionName = region.path("regionName").asText();
            catalog.regionNameByCode.put(code, name);
            catalog.regionCodeByName.put(normalize(name), code);
            // The dropdown shows "Region VIII - Eastern Visayas"; a client may post
            // what it displays, so the label is accepted as well.
            if (!regionName.isBlank() && !regionName.equals(name)) {
                catalog.regionCodeByName.putIfAbsent(normalize(regionName + " \u2013 " + name), code);
            }
        }
        for (JsonNode province : root.path("provinces")) {
            String regionCode = province.path("regionCode").asText();
            String code = province.path("code").asText();
            String name = province.path("name").asText();
            catalog.provinceCodeByName.put(key(regionCode, name), code);
            catalog.provinceNameByCode.put(code, name);
            catalog.regionsWithProvinces.add(regionCode);
        }
        for (JsonNode district : root.path("districts")) {
            String regionCode = district.path("regionCode").asText();
            String code = district.path("code").asText();
            String name = district.path("name").asText();
            catalog.districtCodeByName.put(key(regionCode, name), code);
            catalog.districtNameByCode.put(code, name);
        }
        for (JsonNode city : root.path("cities")) {
            catalog.cities.add(new City(
                    city.path("name").asText(),
                    city.path("regionCode").asText(),
                    textOrNull(city.path("provinceCode")),
                    textOrNull(city.path("districtCode"))));
        }
        return catalog;
    }

    // -------------------------------------------------------------- accessors --

    /** True when the name is one of the ISO 3166-1 countries the form offers. */
    public boolean isKnownCountry(String country) {
        return country != null && countries.contains(normalize(country));
    }

    /** True when the address is a Philippine one (the only structured country). */
    public boolean isPhilippines(String country) {
        return country != null && PHILIPPINES.equalsIgnoreCase(country.trim());
    }

    public int countryCount() {
        return countries.size();
    }

    public int regionCount() {
        return regionNameByCode.size();
    }

    public int cityCount() {
        return cities.size();
    }

    public boolean hasRegion(String region) {
        return resolveRegionCode(region) != null;
    }

    /** True when the PSGC defines provinces for the region (every region but NCR). */
    public boolean regionHasProvinces(String region) {
        String regionCode = resolveRegionCode(region);
        return regionCode != null && regionsWithProvinces.contains(regionCode);
    }

    // ------------------------------------------------------------ validation --

    /**
     * Checks the parent relationships of a Philippine address.
     *
     * @return {@code null} when every part belongs to its parent, otherwise the
     *         reason the address cannot be accepted.
     */
    public String describeProblem(String region, String province, String district, String municipality) {
        String regionCode = resolveRegionCode(region);
        if (regionCode == null) {
            return "Unknown Philippine region: " + trimToEmpty(region) + ".";
        }
        String regionName = regionNameByCode.get(regionCode);

        String provinceCode = null;
        if (isNotBlank(province)) {
            provinceCode = provinceCodeByName.get(key(regionCode, province.trim()));
            if (provinceCode == null) {
                return "Province \"" + province.trim() + "\" does not belong to " + regionName + ".";
            }
        }

        String districtCode = null;
        if (isNotBlank(district)) {
            districtCode = districtCodeByName.get(key(regionCode, district.trim()));
            if (districtCode == null) {
                return "District \"" + district.trim() + "\" does not belong to " + regionName + ".";
            }
        }

        // Neither area level answered: only a city that belongs to no province and
        // no district (City of Isabela, City of Cotabato) is complete that way.
        if (provinceCode == null && districtCode == null
                && !isIndependentCity(regionCode, municipality)) {
            return regionsWithProvinces.contains(regionCode)
                    ? "Province is required for the address."
                    : "District is required for the address.";
        }

        City city = findCity(regionCode, municipality);
        if (city == null) {
            return "Municipality / city \"" + trimToEmpty(municipality) + "\" does not belong to "
                    + regionName + ".";
        }
        if (districtCode != null && !districtCode.equals(city.districtCode())) {
            return "Municipality / city \"" + city.name() + "\" does not belong to district \""
                    + districtNameByCode.get(districtCode) + "\".";
        }
        if (districtCode == null && provinceCode != null && !provinceCode.equals(city.provinceCode())) {
            return "Municipality / city \"" + city.name() + "\" does not belong to province \""
                    + provinceNameByCode.get(provinceCode) + "\".";
        }
        return null;
    }

    /** The first city / municipality of the region that carries the given name. */
    private City findCity(String regionCode, String municipality) {
        String wanted = trimToEmpty(municipality);
        if (wanted.isEmpty()) {
            return null;
        }
        for (City city : cities) {
            if (city.regionCode().equals(regionCode) && city.name().equals(wanted)) {
                return city;
            }
        }
        return null;
    }

    /** True when the city / municipality belongs to no province and no district. */
    private boolean isIndependentCity(String regionCode, String municipality) {
        City city = findCity(regionCode, municipality);
        return city != null && city.provinceCode() == null && city.districtCode() == null;
    }

    // --------------------------------------------------------------- helpers --

    /** PSGC code of a submitted region, accepting its dropdown label as well. */
    private String resolveRegionCode(String region) {
        return regionCodeByName.get(normalize(region));
    }

    private static String key(String parentCode, String name) {
        return trimToEmpty(parentCode) + "|" + trimToEmpty(name);
    }

    /** Lower-cases, trims and folds the dashes of the region label ("Region X - ..."). */
    private static String normalize(String value) {
        return trimToEmpty(value).toLowerCase().replace('\u2013', '-').replaceAll("\\s+", " ");
    }

    private static String trimToEmpty(String value) {
        return value == null ? "" : value.trim();
    }

    private static boolean isNotBlank(String value) {
        return value != null && !value.trim().isEmpty();
    }

    private static String textOrNull(JsonNode node) {
        if (node == null || node.isNull()) {
            return null;
        }
        String value = node.asText();
        return value == null || value.isBlank() ? null : value;
    }
}
