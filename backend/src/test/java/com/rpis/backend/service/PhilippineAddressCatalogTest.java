package com.rpis.backend.service;

import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Covers the PSGC hierarchy the backend validates a submitted address against
 * ({@link PhilippineAddressCatalog}).
 * <p>
 * The cases use real administrative relationships of the bundled dataset:
 * Region X / Northern Mindanao with the province Misamis Oriental and the
 * municipality Naawan, NCR with its four districts, and Region IX with its own
 * independent City of Isabela next to the provinces of the region. The catalog is
 * generated by {@code scripts/build-backend-location-catalog.mjs}, so a refresh of
 * the PSGC data that broke one of these relationships fails here.
 */
class PhilippineAddressCatalogTest {

    private final PhilippineAddressCatalog catalog = PhilippineAddressCatalog.shared();

    @Test
    void theCatalogBundledWithTheApplicationIsAvailable() {
        assertNotNull(catalog, "the address catalog must ship with the backend");
        assertEquals(249, catalog.countryCount());
        assertEquals(17, catalog.regionCount());
        assertEquals(1634, catalog.cityCount());
    }

    @Test
    void countriesComeFromTheSameListTheCountryDropdownOffers() {
        assertTrue(catalog.isKnownCountry("Philippines"));
        assertTrue(catalog.isKnownCountry("Japan"));
        assertTrue(catalog.isKnownCountry("United States"));
        assertFalse(catalog.isKnownCountry("Atlantis"));
        assertFalse(catalog.isKnownCountry(""));
        assertFalse(catalog.isKnownCountry(null));

        assertTrue(catalog.isPhilippines("Philippines"));
        assertFalse(catalog.isPhilippines("Japan"));
    }

    @Test
    void regionsAreResolvedByNameAndByTheLabelTheDropdownShows() {
        assertTrue(catalog.hasRegion("Northern Mindanao"));
        assertTrue(catalog.hasRegion("Region X \u2013 Northern Mindanao"));
        assertTrue(catalog.hasRegion("NCR"));
        assertTrue(catalog.hasRegion("National Capital Region \u2013 NCR"));
        assertFalse(catalog.hasRegion("Northern Mindano"));
        assertFalse(catalog.hasRegion(""));

        assertTrue(catalog.regionHasProvinces("Northern Mindanao"));
        assertFalse(catalog.regionHasProvinces("NCR"));
    }

    @Test
    void aConsistentAddressHasNoProblem() {
        assertNull(catalog.describeProblem("Northern Mindanao", "Misamis Oriental", "", "Naawan"));
        assertNull(catalog.describeProblem("Northern Mindanao", "Misamis Oriental", null, "Naawan"));
        assertNull(catalog.describeProblem("Region X \u2013 Northern Mindanao", "Misamis Oriental", "", "Naawan"));
        // NCR is answered through its district instead of a province.
        assertNull(catalog.describeProblem("NCR", "", "First District", "City of Manila"));
    }

    @Test
    void aPartThatDoesNotBelongToItsParentIsRejected() {
        // Leyte is in Region VIII, not in Region X.
        assertEquals("Province \"Leyte\" does not belong to Northern Mindanao.",
                catalog.describeProblem("Northern Mindanao", "Leyte", "", "Naawan"));
        // Naawan is a municipality of Misamis Oriental, not of Camiguin.
        assertEquals("Municipality / city \"Naawan\" does not belong to province \"Camiguin\".",
                catalog.describeProblem("Northern Mindanao", "Camiguin", "", "Naawan"));
        // City of Manila is in the First District, not in the Second.
        assertEquals("Municipality / city \"City of Manila\" does not belong to district \"Second District\".",
                catalog.describeProblem("NCR", "", "Second District", "City of Manila"));
        // A district of another region.
        assertEquals("District \"First District\" does not belong to Northern Mindanao.",
                catalog.describeProblem("Northern Mindanao", "Misamis Oriental", "First District", "Naawan"));
        // A city of another region.
        assertEquals("Municipality / city \"City of Manila\" does not belong to Northern Mindanao.",
                catalog.describeProblem("Northern Mindanao", "Misamis Oriental", "", "City of Manila"));
        assertEquals("Unknown Philippine region: Atlantis.",
                catalog.describeProblem("Atlantis", "", "First District", "City of Manila"));
    }

    @Test
    void theAreaLevelIsRequiredUnlessTheCityIsIndependent() {
        // A region with provinces needs one of them.
        assertEquals("Province is required for the address.",
                catalog.describeProblem("Northern Mindanao", "", "", "Naawan"));
        // A district-divided region needs a district.
        assertEquals("District is required for the address.",
                catalog.describeProblem("NCR", "", "", "City of Manila"));

        // City of Isabela belongs to no province and no district, so it is complete
        // on its own - and it is not part of any of the region's provinces.
        assertNull(catalog.describeProblem("Zamboanga Peninsula", "", "", "City of Isabela"));
        assertEquals("Municipality / city \"City of Isabela\" does not belong to province \"Zamboanga Del Norte\".",
                catalog.describeProblem("Zamboanga Peninsula", "Zamboanga Del Norte", "", "City of Isabela"));
        // A municipality of the region's province still needs its province.
        assertEquals("Province is required for the address.",
                catalog.describeProblem("Zamboanga Peninsula", "", "", "City of Dipolog"));
        assertNull(catalog.describeProblem("Zamboanga Peninsula", "Zamboanga Del Norte", "", "City of Dipolog"));
    }
}
